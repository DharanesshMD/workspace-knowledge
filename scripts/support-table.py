#!/usr/bin/env python3
"""Render docs/adapters/support.md from docs/adapters/compatibility.json.

The JSON is the single source of truth for which client versions are supported.
`--check` fails when the committed table is stale, so README, setup guide and
completion matrix can link to one generated page instead of repeating it.
"""
import argparse, json, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'docs/adapters/compatibility.json'
TARGET = ROOT / 'docs/adapters/support.md'
LABELS = {
    'implemented-opt-in-certification-pending': 'Opt-in, certification pending',
    'partial': 'Partial',
    'experimental-no-tool-capture': 'Experimental',
    'experimental-private-capture-held': 'Experimental, publication held',
    'implemented-unverified': 'Implemented, unverified',
    'unsupported': 'Unsupported',
    'universal-fallback': 'Fallback',
}
REQUIRED = ('client', 'status', 'os', 'version_policy', 'captured', 'held', 'other_versions')


def cell(text):
    return str(text).replace('|', '\\|').replace('\n', ' ')


def tested(adapter):
    watch = adapter.get('watch') or {}
    return watch.get('tested_version') or adapter.get('version') or 'n/a'


def render(data):
    lines = [
        '# Capture support table',
        '',
        '<!-- Generated by scripts/support-table.py from docs/adapters/compatibility.json. Do not edit by hand. -->',
        '',
        'This is the single place that says which client versions are supported and what is captured or held. '
        'README, the [setup guide](setup.md) and the [completion matrix](../architecture/completion-matrix.md) link here.',
        '',
        '**A version not listed is not supported.** Where a client is version-pinned, other versions are refused with a message that points here; '
        'where it is not, only the tested version is evidence and the weekly release check flags newer releases. '
        'Held sessions never become complete because a later message looks clean. Codex and Antigravity stay experimental; Windows is unsupported; '
        'everything else uses the universal fallback (explicit export and the assistant-written flow).',
        '',
        '| Client | Tested version | OS | Status | What is captured | What is held or limited | Other versions |',
        '|---|---|---|---|---|---|---|',
    ]
    for a in data['adapters']:
        missing = [k for k in REQUIRED if k not in a]
        if missing:
            raise SystemExit(f"{a.get('client', '?')}: missing {', '.join(missing)} in compatibility.json")
        lines.append('| ' + ' | '.join(cell(x) for x in (
            a['client'], tested(a), a['os'], LABELS.get(a['status'], a['status']),
            a['captured'], a['held'], a['other_versions'])) + ' |')
    lines += ['', 'Evidence and limits: [native acceptance](../reviews/2026-10-09-native-capture-acceptance.md), '
              '[native follow-up](../reviews/2026-10-10-native-capture-follow-up.md). '
              'Machine-readable source: [`compatibility.json`](compatibility.json).', '']
    return '\n'.join(lines)


def main(argv=None):
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true', help='fail if docs/adapters/support.md is stale')
    args = parser.parse_args(argv)
    text = render(json.loads(SOURCE.read_text()))
    if args.check:
        if not TARGET.exists() or TARGET.read_text() != text:
            print('docs/adapters/support.md is stale; run scripts/support-table.py', file=sys.stderr)
            return 1
        return 0
    TARGET.write_text(text)
    return 0


if __name__ == '__main__':
    sys.exit(main())
